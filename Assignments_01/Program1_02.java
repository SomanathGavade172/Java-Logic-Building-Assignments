// 2. Program to print 5 times "Marvellous" on screen.

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Class Name      : Display
//  Description     : Contains function to display "Marvellous" five times.
//  Input            : None
//  Output           : Displays "Marvellous" on screen
//  Author           : Gavade Somanath Vilas
//  Date             : 11/05/2026
//
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Display
{

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name    : DisplayX
//  Description      : Displays "Marvellous" five times on screen.
//  Input            : None
//  Output           : Prints "Marvellous"
//  Date             : 11/05/2026
//  Time Complexity  : O(N)
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    public void DisplayX()
    {
        int iCnt = 0;

        for(iCnt = 1; iCnt <= 5; iCnt++)
        {
            System.out.println("Marvellous");
        }
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Class Name      : Program1_02
//  Description     : This application displays "Marvellous" five times on screen.
//
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Program1_02
{
    public static void main(String Arg[])
    {
        Display dobj = new Display();

        dobj.DisplayX();
    }
}