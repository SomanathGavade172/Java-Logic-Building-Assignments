// 3. Program to print 5 to 1 numbers on screen.

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Class Name      : Display
//  Description     : Contains function to display numbers from 5 to 1.
//  Input            : None
//  Output           : Displays numbers from 5 to 1
//  Author           : Gavade Somanath Vilas
//  Date             : 11/05/2026
//
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Display
{

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name    : DisplayX
//  Description      : Displays numbers from 5 to 1 on screen.
//  Input            : None
//  Output           : Prints numbers from 5 to 1
//  Date             : 11/05/2026
//  Time Complexity  : O(N)
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    public void DisplayX()
    {
        int iCnt = 0;

        for(iCnt = 5; iCnt >= 1; iCnt--)
        {
            System.out.println(iCnt);
        }
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Class Name      : Program1_03
//  Description     : This application displays numbers from 5 to 1 on screen.
//
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Program1_03
{
    public static void main(String Arg[])
    {
        Display dobj = new Display();

        dobj.DisplayX();
    }
}