// 2. Accept one number from user and print that number of * on screen using while loop.

import java.util.*;

/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Class Name      : Number
//  Description     : Contains function to display * on screen.
//  Input            : Integer
//  Output           : Displays * pattern
//  Author           : Gavade Somanath Vilas
//  Date             : 11/05/2026
//
/////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

class Number
{

///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name    : Display
//  Description      : Displays given number of * on screen using while loop.
//  Input            : Integer
//  Output           : Prints * pattern
//  Date             : 11/05/2026
//  Time Complexity  : O(N)
//
///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

    public void Display(int iNo)
    {
        int iCnt = 0;

        if(iNo < 0)
        {
            iNo = -(iNo);
        }

        iCnt = 1;

        while(iCnt <= iNo)
        {
            System.out.println("*");
            iCnt++;
        }
    }
}

